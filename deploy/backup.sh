#!/bin/sh
# Копия базы заявок плюс проверка, что копия рабочая.
#
# Отдельным файлом, а не одной строкой в расписании, нарочно: строку в crontab нельзя
# ни прочитать спокойно, ни поправить, ни запустить руками, чтобы посмотреть, что она
# делает. Файл можно.
#
# Что подставить своё — одно место: путь к проекту.
#
# Как поставить на сервер (команды выполняет человек, не агент):
#   1. Скопировать файл на сервер, например в <путь-к-проекту>/deploy/backup.sh
#      (он и так приедет туда вместе с кодом при git clone или git pull)
#   2. Сделать исполняемым: chmod +x <путь-к-проекту>/deploy/backup.sh
#   3. Проверить руками: <путь-к-проекту>/deploy/backup.sh
#   4. Поставить в расписание: crontab -e и строка
#      0 3 * * * <путь-к-проекту>/deploy/backup.sh >> <путь-к-проекту>/backups/backup.log 2>&1
#      — каждую ночь в 3:00, вывод дописывается в лог рядом с копиями.
#
# В расписании стоит вызов файла, а не сама команда копирования: если понадобится
# поменять логику бэкапа, правится файл, а строка в crontab остаётся прежней. Заодно
# снимается ловушка с символом процента: в crontab его пришлось бы экранировать, а в
# файле сценария он живёт как есть.

set -e

PROJECT_DIR="<путь-к-проекту>"

# Сколько дней держим копии. Бэкап без чистки со временем сам становится проблемой:
# копия каждую ночь — это 365 файлов базы за год, на том же диске, где лежит и сама
# база. Две недели назад — это уже не запас, это мусор.
KEEP_DAYS=14

DB_FILE="$PROJECT_DIR/radar.db"
BACKUPS_DIR="$PROJECT_DIR/backups"
COPY="$BACKUPS_DIR/radar-$(date +%F).db"

mkdir -p "$BACKUPS_DIR"

if [ ! -f "$DB_FILE" ]; then
    echo "$(date +'%F %T') база не найдена: $DB_FILE"
    exit 1
fi

cp "$DB_FILE" "$COPY"

# Копия без проверки — это просто файл, в котором вы уверены на веру. Открываем её и
# считаем заявки: если файл битый или скопировался наполовину, здесь это и выяснится.
# Считаем через python3, а не через утилиту sqlite3: python3 на сервере есть точно,
# он нужен самому проекту, а отдельную консольную утилиту пришлось бы ставить.
COUNT=$(python3 -c "import sqlite3, sys; print(sqlite3.connect(sys.argv[1]).execute('SELECT count(*) FROM requests').fetchone()[0])" "$COPY")

echo "$(date +'%F %T') копия готова: $COPY, заявок в ней: $COUNT"

# Убираем копии старше KEEP_DAYS дней. Маска ловит только копии вида
# radar-2026-09-28.db — саму базу radar.db она не заденет, в её имени нет дефиса.
# -print -delete печатает то, что удаляет, поэтому строки можно просто посчитать.
DELETED=$(find "$BACKUPS_DIR" -name 'radar-*.db' -type f -mtime +"$KEEP_DAYS" -print -delete | wc -l)
if [ "$DELETED" -gt 0 ]; then
    echo "$(date +'%F %T') удалено копий старше $KEEP_DAYS дней: $DELETED"
fi
