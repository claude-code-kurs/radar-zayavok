"""Настройка логов — одна для юзербота и для классификатора.

Формат один на оба процесса нарочно: когда через неделю понадобится понять, почему
заявки перестали приходить, читать придётся оба лога подряд, и разный формат в них
мешает. Время в строке нужно и локально, и на сервере: `journalctl` ставит своё,
но при запуске руками в терминале его не будет.
"""

import logging


def setup():
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(levelname)s %(message)s",
        datefmt="%Y-%m-%d %H:%M:%S",
    )
